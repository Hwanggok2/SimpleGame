        public static string DifficultyName(GameDifficulty difficulty)
        {
            return difficulty switch
            {
                GameDifficulty.Easy => DifficultyEasyName,
                GameDifficulty.Normal => DifficultyNormalName,
                GameDifficulty.Hard => DifficultyHardName,
                _ => DifficultyNormalName
            };
        }

        public static string DifficultyDescription(GameDifficulty difficulty)
        {
            return difficulty switch
            {
                GameDifficulty.Easy => DifficultyEasyDescription,
                GameDifficulty.Normal => DifficultyNormalDescription,
                GameDifficulty.Hard => DifficultyHardDescription,
                _ => DifficultyNormalDescription
            };
        }

        public static string StageName(string stageId)
        {
            return $"STAGE_{NormalizeId(stageId)}_NAME";
        }

        public static string StageDescription(string stageId)
        {
            return $"STAGE_{NormalizeId(stageId)}_DESCRIPTION";
        }

        public static string EnemyName(string enemyId)
        {
            return enemyId switch
            {
                "GoblinMelee" =>
                    EnemyGoblinMeleeName,
                "GoblinRanged" =>
                    EnemyGoblinRangedName,
                PrototypeEnemyDefinitions.ShieldSkeletonId =>
                    EnemyShieldSkeletonName,
                PrototypeEnemyDefinitions.GoblinBossId =>
                    EnemyGoblinBossName,
                PrototypeEnemyDefinitions.MushroomBossId =>
                    EnemyMushroomBossName,
                PrototypeEnemyDefinitions.FlyingEyeId =>
                    EnemyFlyingEyeName,
                PrototypeEnemyDefinitions.FlyingEyeBossId =>
                    EnemyFlyingEyeBossName,
                PrototypeEnemyDefinitions.SkeletonBossId =>
                    EnemySkeletonBossName,
                _ => EnemyGenericName
            };
        }

